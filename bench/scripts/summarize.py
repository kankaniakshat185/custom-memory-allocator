#!/usr/bin/env python3
"""Builds docs/results/timing-summary.md from the raw per-rep timing CSVs.

Statistic (ADR-008): median ns/op across reps, with spread as IQR / median.
Max-min spread is dominated by single outlier reps on this machine, so it is
not used for the noisy-row threshold (IQR > 10%).
    python3 bench/scripts/summarize.py [results_dir]
"""
import collections
import csv
import sys
from pathlib import Path

out_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "docs/results")
rows = collections.defaultdict(list)
for name in ("timing-current-raw.csv", "timing-phases-raw.csv"):
    path = out_dir / name
    if path.exists():
        for r in csv.reader(path.open()):
            rows[(r[0], r[1], r[2])].append((float(r[4]), int(r[5])))


def q(v, p):
    v = sorted(v)
    i = p * (len(v) - 1)
    lo = int(i)
    hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (i - lo)


lines = [
    "# Timing summary",
    "",
    "Generated by `bench/scripts/summarize.py` from the raw CSVs in this folder. "
    "Median ns/op over reps; IQR% = interquartile range / median. Rows with IQR% > 10 "
    "are marked noisy. Method: [ADR-008](../adr/008-benchmark-methodology.md). "
    "Machine state: [timing-machine-state.txt](timing-machine-state.txt).",
    "",
    "| Label | Allocator | Workload | Reps | Median ns/op | IQR % | Failures/rep | Note |",
    "|---|---|---|---|---|---|---|---|",
]
for (label, alloc, wl), v in rows.items():
    times = [t for t, _ in v]
    fails = max(f for _, f in v)
    med = q(times, 0.5)
    iqr = 100 * (q(times, 0.75) - q(times, 0.25)) / med
    notes = []
    if iqr > 10:
        notes.append("noisy")
    if fails:
        notes.append("OOM failures: not comparable as speed")
    lines.append(f"| {label} | {alloc} | {wl} | {len(times)} | {med:.2f} | {iqr:.1f} | {fails} | {', '.join(notes)} |")
(out_dir / "timing-summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
